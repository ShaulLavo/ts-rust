// Generates environment-specific ESM exports and declarations from the pinned
// TypeScript package. The implementation remains the Rust-backed namespace.
// Usage: node scripts/generate-classic-entry.mjs <typescript-package-directory>
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

const packageDirectory = process.argv[2];
if (!packageDirectory) throw new Error("pass the reference typescript package directory");
const root = resolve(packageDirectory);
const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
if (manifest.version !== "6.0.3" || manifest.gitHead !== "050880ce59e30b356b686bd3144efe24f875ebc8") {
    throw new Error(`expected typescript 6.0.3 (050880ce), found ${manifest.version} (${manifest.gitHead})`);
}
const require = createRequire(import.meta.url);
const ts = require(join(root, "lib/typescript.js"));
const declarations = readFileSync(join(root, "lib/typescript.d.ts"), "utf8");
const hash = text => createHash("sha256").update(text).digest("hex");
const provenance = `// Generated by scripts/generate-classic-entry.mjs from typescript@${manifest.version} (gitHead ${manifest.gitHead}).\n`;
const names = Object.keys(ts).sort();
for (const name of names) {
    if (!ts.isIdentifierText(name, ts.ScriptTarget.Latest)) throw new Error(`invalid export name ${name}`);
}
for (const environment of ["node", "browser"]) {
    writeFileSync(new URL(`../classic-${environment}.js`, import.meta.url),
        provenance
        + `// Export names from lib/typescript.js sha256 ${hash(readFileSync(join(root, "lib/typescript.js")))}.\n`
        + `import { loadModule } from "./${environment}.js";\n`
        + `import { createClassicNamespace } from "./classic-namespace.js";\n\n`
        + `const ts = createClassicNamespace(await loadModule());\n\nexport default ts;\n`
        + `export const {\n${names.map(name => `    ${name},`).join("\n")}\n} = ts;\n`);
    writeFileSync(new URL(`../classic-${environment}.d.ts`, import.meta.url),
        provenance + 'export * from "./index.js";\nexport { default } from "./index.js";\n');
}
const source = ts.createSourceFile("typescript.d.ts", declarations, ts.ScriptTarget.Latest, true);
const namespace = source.statements.find(statement => ts.isModuleDeclaration(statement) && statement.name.text === "ts");
if (!namespace || !ts.isModuleBlock(namespace.body)) throw new Error("reference ts namespace changed");
const publicNames = new Set();
for (const statement of namespace.body.statements) {
    if (ts.isVariableStatement(statement)) {
        for (const declaration of statement.declarationList.declarations) {
            if (!ts.isIdentifier(declaration.name)) throw new Error("reference declaration binding changed");
            publicNames.add(declaration.name.text);
        }
        continue;
    }
    if (!statement.name || !ts.isIdentifier(statement.name)) throw new Error("reference namespace member changed");
    publicNames.add(statement.name.text);
}
const closing = /export = ts;\s*$/;
if (!closing.test(declarations)) throw new Error("reference declaration export changed");
const aliases = Array.from(publicNames).sort().map(name => `export import ${name} = ts.${name};`).join("\n");
writeFileSync(new URL("../index.d.ts", import.meta.url),
    provenance + `// lib/typescript.d.ts sha256 ${hash(declarations)}. Microsoft TypeScript is Apache-2.0; its notice follows.\n`
    + declarations.replace(closing, `${aliases}\nexport default ts;\n`));
writeFileSync(new URL("../classic.d.ts", import.meta.url),
    provenance + 'export * from "./index.js";\nexport { default } from "./index.js";\n');
console.log(JSON.stringify({ referenceVersion: manifest.version, namedRuntimeExports: names.length, namedDeclarations: publicNames.size }));
