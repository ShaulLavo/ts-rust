import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { test } from "node:test";

const generated = existsSync(new URL("../classic-services.js", import.meta.url));
const skip = generated ? false : "classic-services.js is generated by scripts/generate-classic-services.mjs from typescript@6.0.3";

test("the classic dispatch runs on Rust programs and keeps old source files", { skip }, async () => {
    const { default: ts } = await import("../classic.js");
    const text = new Map([["/a.ts", 'import { value } from "./b"; export const result: number = value;'], ["/b.ts", "export const value = 1;"]]);
    const versions = new Map([["/a.ts", "1"], ["/b.ts", "1"]]);
    const host = {
        getCompilationSettings: () => ({ noLib: true, strict: true }),
        getScriptFileNames: () => ["/a.ts"],
        getScriptVersion: path => versions.get(path),
        getScriptSnapshot: path => text.has(path) ? ts.ScriptSnapshot.fromString(text.get(path)) : undefined,
        getCurrentDirectory: () => "/",
        getDefaultLibFileName: () => "/lib.d.ts",
        useCaseSensitiveFileNames: () => true,
        readFile: path => text.get(path),
        fileExists: path => text.has(path),
    };
    const service = ts.createLanguageService(host);
    try {
        assert.deepEqual(service.getSemanticDiagnostics("/a.ts"), []);
        const first = service.getProgram();
        assert.equal(service.getProgram(), first, "an unchanged host keeps its program");
        const oldB = first.getSourceFile("/b.ts");
        text.set("/b.ts", 'export const value = "edited";');
        versions.set("/b.ts", "2");
        const diagnostics = service.getSemanticDiagnostics("/a.ts");
        assert.deepEqual(diagnostics.map(diagnostic => diagnostic.code), [2322]);
        const program = service.getProgram();
        assert.notEqual(program, first);
        assert.equal(diagnostics[0].file, program.getSourceFile("/a.ts"));
        assert.equal(program.getSourceFile("/a.ts"), first.getSourceFile("/a.ts"), "an unchanged version keeps its source file");
        assert.notEqual(program.getSourceFile("/b.ts"), oldB);
        assert.equal(oldB.text, "export const value = 1;");
        assert.equal(oldB.statements[0].declarationList.declarations[0].name.text, "value");
        assert.deepEqual(service.getSyntacticDiagnostics("/a.ts"), []);
        assert.deepEqual(service.getNavigationTree("/a.ts").childItems.map(item => item.text), ["result", "value"]);
    } finally { service.dispose(); }
    assert.throws(() => ts.createTypeChecker({}), /not part of this compiler/);
    assert.throws(() => ts.bindSourceFile(undefined, {}), /not part of this compiler/);
});

test("programs read libraries from the host and expose classic resolutions", { skip }, async () => {
    const { default: ts } = await import("../classic.js");
    const lib = "/Home/Lib";
    const text = new Map([
        [`${lib}/lib.es2025.full.d.ts`, '/// <reference no-default-lib="true"/>\n/// <reference lib="es5" />\ninterface Marker {}'],
        [`${lib}/lib.es5.d.ts`, '/// <reference no-default-lib="true"/>\ninterface Array<T> { length: number } interface Boolean {} interface Function {} interface IArguments {} interface Number {} interface Object {} interface RegExp {} interface String {} interface CallableFunction {} interface NewableFunction {}'],
        ["/src/A.ts", 'import { value } from "./b"; import missing from "./missing"; export const marker: Marker = {}; export { value };'],
        ["/src/b.ts", "export const value = 1;"],
    ]);
    const host = {
        getCompilationSettings: () => ({}),
        getScriptFileNames: () => ["/src/A.ts"],
        getScriptVersion: () => "1",
        getScriptSnapshot: path => text.has(path) ? ts.ScriptSnapshot.fromString(text.get(path)) : undefined,
        getCurrentDirectory: () => "/",
        getDefaultLibFileName: options => `${lib}/${ts.getDefaultLibFileName(options)}`,
        useCaseSensitiveFileNames: () => false,
        readFile: path => text.get(path),
        fileExists: path => text.has(path),
    };
    const service = ts.createLanguageService(host);
    try {
        assert.deepEqual(service.getSemanticDiagnostics("/src/A.ts").map(diagnostic => diagnostic.code), [2307]);
        const program = service.getProgram();
        const libraries = program.getSourceFiles().filter(file => program.isSourceFileDefaultLibrary(file));
        // Classic `compareDefaultLibFiles` puts es5 before the target's library.
        assert.deepEqual(libraries.map(file => [file.fileName, file.path, file.hasNoDefaultLib]), [
            [`${lib}/lib.es5.d.ts`, "/home/lib/lib.es5.d.ts", false],
            [`${lib}/lib.es2025.full.d.ts`, "/home/lib/lib.es2025.full.d.ts", false],
        ]);
        assert.deepEqual(Array.from(program.resolvedLibReferences), [["lib.es5.d.ts", { resolution: { resolvedModule: undefined }, actual: `${lib}/lib.es5.d.ts` }]]);
        const file = program.getSourceFile("/src/A.ts");
        const seen = [];
        program.forEachResolvedModule((resolution, name, _mode, path) => seen.push([path, name, resolution.resolvedModule?.resolvedFileName]));
        assert.deepEqual(seen, [["/src/a.ts", "./b", "/src/b.ts"], ["/src/a.ts", "./missing", undefined]]);
        const resolution = program.getResolvedModuleFromModuleSpecifier(file.statements[0].moduleSpecifier);
        assert.equal(resolution.resolvedModule.resolvedFileName, "/src/b.ts");
        assert.equal(program.getResolvedModuleFromModuleSpecifier(file.statements[0].moduleSpecifier, file), resolution, "one resolution object per name");
        assert.equal(program.getAutomaticTypeDirectiveResolutions().size(), 0);
        assert.deepEqual(program.getAutomaticTypeDirectiveNames(), []);
    } finally { service.dispose(); }
});

test("checker members answer as TypeScript 6.0.3 does", { skip }, async () => {
    const { default: ts } = await import("../classic.js");
    const text = 'declare module "ambient" { export const x: number; }\nclass C { m() { return this; } }\nfunction f(a: number) { return arguments.length + a; }\nconst arr: string[] = []; f(1);\ninterface I { [k: string]: number; readonly [n: number]: 1 }';
    const host = {
        getCompilationSettings: () => ({ noLib: true }), getScriptFileNames: () => ["/a.ts"], getScriptVersion: () => "1",
        getScriptSnapshot: path => path === "/a.ts" ? ts.ScriptSnapshot.fromString(text) : undefined,
        getCurrentDirectory: () => "/", getDefaultLibFileName: () => "/lib.d.ts", useCaseSensitiveFileNames: () => true,
        readFile: path => path === "/a.ts" ? text : undefined, fileExists: path => path === "/a.ts",
    };
    const service = ts.createLanguageService(host);
    try {
        // Expected values were read from typescript@6.0.3 on the same input.
        const program = service.getProgram();
        const checker = program.getTypeChecker();
        const file = program.getSourceFile("/a.ts");
        assert.deepEqual(checker.getAmbientModules().map(symbol => symbol.name), ['"ambient"']);
        assert.equal(checker.getAmbientModules(), checker.getAmbientModules());
        const method = file.statements[1].members[0];
        const thisExpression = method.body.statements[0].expression;
        assert.equal(checker.typeToString(checker.tryGetThisTypeAt(thisExpression)), "this");
        assert.equal(checker.getSymbolsInScope(method.body, ts.SymbolFlags.Value).map(symbol => symbol.name).sort().join(","), '"ambient",C,arguments,arr,f,globalThis,undefined');
        const f = checker.resolveName("f", thisExpression, ts.SymbolFlags.Value, false);
        assert.equal(f.name, "f");
        assert.equal(checker.resolveName("nope", thisExpression, ts.SymbolFlags.Value, false), undefined);
        assert.deepEqual([checker.isUnknownSymbol(f), checker.isUndefinedSymbol(f)], [false, false]);
        assert.equal(checker.isUndefinedSymbol(checker.resolveName("undefined", thisExpression, ts.SymbolFlags.Value, false)), true);
        assert.deepEqual([checker.containsArgumentsReference(file.statements[2]), checker.containsArgumentsReference(method)], [true, false]);
        const candidates = [];
        const signature = checker.getResolvedSignatureForSignatureHelp(file.statements[4].expression, candidates, 1);
        assert.deepEqual([checker.signatureToString(signature), candidates.length], ["(a: number): any", 1]);
        const infos = checker.getIndexInfosOfType(checker.getTypeAtLocation(file.statements[5].name));
        assert.deepEqual(infos.map(info => [checker.typeToString(info.keyType), checker.typeToString(info.type), info.isReadonly, info.declaration.kind]),
            [["string", "number", false, ts.SyntaxKind.IndexSignature], ["number", "1", true, ts.SyntaxKind.IndexSignature]]);
        assert.equal(checker.getIndexInfoOfType(checker.getTypeAtLocation(file.statements[5].name), ts.IndexKind.String), infos[0]);
    } finally { service.dispose(); }
});

test("an unsupported root is not missing, and synthesized nodes answer through their originals", { skip }, async () => {
    const { default: ts } = await import("../classic.js");
    const text = new Map([["/a.ts", "export const x = 0;"], ["/a.js", "exports.x = 0;"]]);
    const host = {
        getCompilationSettings: () => ({ noLib: true }), getScriptFileNames: () => ["/a.ts", "/a.js"], getScriptVersion: () => "1",
        getScriptSnapshot: path => text.has(path) ? ts.ScriptSnapshot.fromString(text.get(path)) : undefined,
        getCurrentDirectory: () => "/", getDefaultLibFileName: () => "/lib.d.ts", useCaseSensitiveFileNames: () => true,
        readFile: path => text.get(path), fileExists: path => text.has(path),
    };
    const service = ts.createLanguageService(host);
    try {
        const program = service.getProgram();
        assert.deepEqual(Array.from(program.getMissingFilePaths()), []);
        assert.equal(service.getProgram(), program, "classic keeps a program whose unsupported root exists");
        const checker = program.getTypeChecker();
        const declaration = program.getSourceFile("/a.ts").statements[0].declarationList.declarations[0];
        const clone = ts.getSynthesizedDeepClone(declaration.name);
        assert.equal(checker.getSymbolAtLocation(clone), checker.getSymbolAtLocation(declaration.name));
        assert.equal(checker.typeToString(checker.getTypeAtLocation(clone)), "0");
        assert.equal(checker.getSignatureFromDeclaration(ts.factory.createFunctionDeclaration(undefined, undefined, "f", undefined, [], undefined, undefined)), undefined);
        assert.equal(program.useCaseSensitiveFileNames(), true);
        assert.equal(program.fileExists("/a.js"), true);
        assert.equal(program.isEmittedFile("/a.js"), true);
    } finally { service.dispose(); }
});
