// Writes classic-options.js: the compiler option declarations of a classic
// TypeScript release, for translating classic CompilerOptions objects.
//
// usage: node scripts/generate-classic-options.mjs <typescript-package-directory>
// Use the typescript@6.0.3 package (gitHead 050880ce).
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const packageDirectory = process.argv[2];
if (!packageDirectory) throw new Error("pass the reference typescript package directory");
const require = createRequire(import.meta.url);
const ts = require(join(packageDirectory, "lib/typescript.js"));
const manifest = require(join(packageDirectory, "package.json"));

function kind(type) {
    if (typeof type === "string") return { kind: type };
    return { kind: "enum", values: Object.fromEntries(type) };
}

const declarations = ts.optionDeclarations.map(option => {
    const result = { name: option.name, ...kind(option.type) };
    if (option.element) result.element = kind(option.element.type);
    return result;
});
const header = `// Apache-2.0. Generated by scripts/generate-classic-options.mjs from typescript@${manifest.version}`
    + ` (gitHead ${manifest.gitHead}): \`optionDeclarations\` of src/compiler/commandLineParser.ts.\n`;
writeFileSync(new URL("../classic-options.js", import.meta.url),
    `${header}export const optionDeclarations = ${JSON.stringify(declarations, null, 1)};\n`);
