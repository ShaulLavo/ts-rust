import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { test } from "node:test";

const generated = existsSync(new URL("../classic-services.js", import.meta.url));
const skip = generated ? false : "classic-services.js is generated by scripts/generate-classic-services.mjs from typescript@6.0.3";

test("the classic dispatch runs on Rust programs and keeps old source files", { skip }, async () => {
    const { default: ts } = await import("../classic.js");
    const text = new Map([["/a.ts", 'import { value } from "./b"; export const result: number = value;'], ["/b.ts", "export const value = 1;"]]);
    const versions = new Map([["/a.ts", "1"], ["/b.ts", "1"]]);
    const host = {
        getCompilationSettings: () => ({ noLib: true, strict: true }),
        getScriptFileNames: () => ["/a.ts"],
        getScriptVersion: path => versions.get(path),
        getScriptSnapshot: path => text.has(path) ? ts.ScriptSnapshot.fromString(text.get(path)) : undefined,
        getCurrentDirectory: () => "/",
        getDefaultLibFileName: () => "/lib.d.ts",
        useCaseSensitiveFileNames: () => true,
        readFile: path => text.get(path),
        fileExists: path => text.has(path),
    };
    const service = ts.createLanguageService(host);
    try {
        assert.deepEqual(service.getSemanticDiagnostics("/a.ts"), []);
        const first = service.getProgram();
        assert.equal(service.getProgram(), first, "an unchanged host keeps its program");
        const oldB = first.getSourceFile("/b.ts");
        text.set("/b.ts", 'export const value = "edited";');
        versions.set("/b.ts", "2");
        const diagnostics = service.getSemanticDiagnostics("/a.ts");
        assert.deepEqual(diagnostics.map(diagnostic => diagnostic.code), [2322]);
        const program = service.getProgram();
        assert.notEqual(program, first);
        assert.equal(diagnostics[0].file, program.getSourceFile("/a.ts"));
        assert.equal(program.getSourceFile("/a.ts"), first.getSourceFile("/a.ts"), "an unchanged version keeps its source file");
        assert.notEqual(program.getSourceFile("/b.ts"), oldB);
        assert.equal(oldB.text, "export const value = 1;");
        assert.equal(oldB.statements[0].declarationList.declarations[0].name.text, "value");
        assert.deepEqual(service.getSyntacticDiagnostics("/a.ts"), []);
        assert.deepEqual(service.getNavigationTree("/a.ts").childItems.map(item => item.text), ["result", "value"]);
    } finally { service.dispose(); }
    assert.throws(() => ts.createTypeChecker({}), /not part of this compiler/);
    assert.throws(() => ts.bindSourceFile(undefined, {}), /not part of this compiler/);
});
